def check_goldens(spec, gold):
    for g in gold['galaxies']:
        p = np.array(g['params'])
        if spec.seeded:
            out = spec.simulate(g['n'], p, np.random.default_rng(g['seed']))
        else:
            agama.setRandomSeed(g['seed'])
            out = spec.simulate(g['n'], p)
        assert out is not None, (spec.name, g['seed'])
        posvel, _ = out
        digest = hashlib.sha256(posvel.tobytes()).hexdigest()
        assert digest == g['sha256'], \
            f'{spec.name} seed {g["seed"]}: physics changed'
        assert spec.preprocess(posvel, p) is not None, \
            f'{spec.name}: cut changed'
    rng = np.random.default_rng(7)
    draws = runner.iter_params(spec, 2, 100, rng)
    for (p_gold, n_gold), (p, n, _) in zip(gold['stream_seed7'], draws):
        assert np.array_equal(p, p_gold) and n == n_gold, \
            f'{spec.name}: prior draw changed'


def check_tsnpe_adapter(spec):
    """model_to_sim must invert the stored-column definition of the
    model row."""
    rng = np.random.default_rng(1)
    p, _ = spec.draw(rng, 100)
    cols = spec.columns(p, {})
    row = np.array([[cols[n] for n in spec.tsnpe.param_names]
                    + [cols['stellar_log_rstar_kpc']]])
    assert np.allclose(spec.tsnpe.model_to_sim(row)[0], p), spec.name
    for n in spec.tsnpe.cond_columns:
        assert np.isclose(cols[n], cols['stellar_log_rstar_kpc']), \
            (spec.name, n)


def check_datasets():
    for d in sorted(glob.glob(f'{DATASETS_ROOT}/*/')):
        name = os.path.basename(d.rstrip('/'))
        # The directory's own config.0.json is the authority on which spec
        # simulated it; the registry's `datasets` lists are the fallback.
        spec = dsph_sims.get_spec(
            dsph_sims.dataset_model_spec(DATASETS_ROOT, name))
        for c in glob.glob(f'{d}config.*.json'):
            cfg = json.load(open(c))
            assert cfg['prior_min'] == list(spec.prior_min), (name, c)
            assert cfg['prior_max'] == list(spec.prior_max), (name, c)
            assert cfg.get('model_spec') == spec.name, (name, c)
            assert cfg.get('prior_constraint') == spec.constraint_text, \
                (name, c)
        print(f'  {name} == {spec.name}')


if __name__ == '__main__':
    for name, spec in dsph_sims.SPECS.items():
        if name not in GOLDENS:
            # A new spec: nothing to compare against until its physics is
            # final and goldens are recorded (see the module docstring).
            print(f'  {name}: NO GOLDENS yet - physics unverified')
            continue
        check_goldens(spec, GOLDENS[name])
        if spec.tsnpe is not None:
            check_tsnpe_adapter(spec)
        print(f'  {name}: goldens ok'
              + (', tsnpe adapter ok' if spec.tsnpe else ''))
    if os.path.isdir(DATASETS_ROOT):
        check_datasets()
    print('OK')
